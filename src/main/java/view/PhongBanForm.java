    // Hàm xử lý logic tìm kiếm riêng biệt giống trong ảnh
    private void tim(String keyword) {
        // 1. Nếu từ khóa rỗng, tải lại toàn bộ danh sách gốc
        if (keyword.isEmpty()) {
            loadTable(); 
            return;
        }
        
        // 2. Xóa sạch bảng hiện tại
        tblModel.setRowCount(0);
        
        // 3. Gọi hàm tìm kiếm từ DAO (Hàm DAO ở Bước 2 bài trước mình gửi)
        java.util.List<model.PhongBan> list = dao.searchPhongBan(keyword);
        
        // 4. Kiểm tra và đổ dữ liệu
        if (list.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Không tìm thấy phòng ban nào có chữ: " + keyword);
        } else {
            for (model.PhongBan pb : list) {
                tblModel.addRow(new Object[]{
                    pb.getMaPB(),
                    pb.getTenPB(),
                    pb.getDienThoai(),
                    pb.getGhiChu()
                });
            }
        }
    }
