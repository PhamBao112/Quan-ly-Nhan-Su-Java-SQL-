    private void btnthempbActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnthempbActionPerformed
        // 1. Lấy dữ liệu từ các ô Textbox
        String tenPB = txttenpb.getText().trim();
        String dienThoai = txtsdtpb.getText().trim();
        String ghiChu = txaghichupb.getText().trim();

        // 2. Bắt lỗi không được để trống Tên phòng ban
        if (tenPB.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập tên phòng ban!");
            txttenpb.requestFocus();
            return;
        }

        // 3. Kết nối CSDL và gọi Stored Procedure
        try {
            java.sql.Connection conn = util.DBConnection.getConnection();
            
            String sql = "{CALL sp_ThemPhongBan(?, ?, ?)}";
            java.sql.CallableStatement cs = conn.prepareCall(sql);
            
            cs.setString(1, tenPB);
            cs.setString(2, dienThoai);
            cs.setString(3, ghiChu);
            
            // Thực thi thủ tục
            cs.execute();
            
            // Thông báo thành công
            javax.swing.JOptionPane.showMessageDialog(this, "Thêm phòng ban thành công!");
            
            loadTable(); // Tải lại bảng để thấy dữ liệu mới xuất hiện ngay lập tức
            btnlamlaipbActionPerformed(evt); // Gọi luôn nút Làm Lại để xóa trắng các ô chữ cho gọn
            
            // Đóng kết nối
            cs.close();
            conn.close();
            
        } catch (java.awt.HeadlessException | java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Lỗi Thêm: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnthempbActionPerformed

    private void tbphongbanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbphongbanMouseClicked
        int row = tbphongban.getSelectedRow();
        if (row >= 0) {
            // Lấy dữ liệu từ các cột của dòng đó và đẩy lên các TextBox
            txtmapb.setText(tbphongban.getValueAt(row, 0).toString());
            txttenpb.setText(tbphongban.getValueAt(row, 1).toString());
            
            Object sdt = tbphongban.getValueAt(row, 2);
            txtsdtpb.setText(sdt != null ? sdt.toString() : "");
            
            Object ghiChu = tbphongban.getValueAt(row, 3);
            txaghichupb.setText(ghiChu != null ? ghiChu.toString() : "");
        }
    }//GEN-LAST:event_tbphongbanMouseClicked

    private void btnxoapbActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnxoapbActionPerformed
        // 1. Lấy chuỗi từ ô nhập Mã PB
        String maPBStr = txtmapb.getText().trim();

        // 2. Kiểm tra rỗng 
        if (maPBStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn hoặc nhập mã phòng ban cần xóa!");
            return;
        }

        int maPB;
        
        // 3. Kiểm tra định dạng số 
        try {
            maPB = Integer.parseInt(maPBStr);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Mã phòng ban phải là số!");
            return;
        }

        // 4. Hiển thị hộp thoại xác nhận
        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this, 
                "Bạn có chắc muốn xóa phòng ban này?", 
                "Xác nhận", 
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        // 5. Nếu chọn YES (Đồng ý xóa)
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            try {
                // Gọi hàm deletePhongBan từ DAO 
                if (dao.deletePhongBan(maPB)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Xóa phòng ban thành công!");
                    loadTable(); 
                    
                    // Làm sạch các ô text
                    txtmapb.setText("");
                    txttenpb.setText("");
                    txtsdtpb.setText("");
                    txaghichupb.setText("");
                } else {
                    // Nếu DAO trả về false 
                    javax.swing.JOptionPane.showMessageDialog(this, "Xóa thất bại! Vui lòng kiểm tra lại dữ liệu.");
                }
            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Lỗi hệ thống: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnxoapbActionPerformed

    private void btnsuapbActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsuapbActionPerformed
        // 1. Kiểm tra xem người dùng đã chọn phòng ban trên bảng chưa
        String maPBStr = txtmapb.getText().trim();
        if (maPBStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng click chọn một phòng ban trên bảng để sửa!");
            return;
        }

        // 2. Lấy dữ liệu mới từ các ô nhập liệu
        String tenPB = txttenpb.getText().trim();
        String dienThoai = txtsdtpb.getText().trim();
        String ghiChu = txaghichupb.getText().trim();

        // 3. Bắt lỗi không được để trống Tên phòng ban
        if (tenPB.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Tên phòng ban không được để trống!");
            txttenpb.requestFocus();
            return;
        }

        // 4. Ép kiểu Mã PB sang số nguyên và đóng gói vào Object
        try {
            int maPB = Integer.parseInt(maPBStr);
            model.PhongBan pb = new model.PhongBan(maPB, tenPB, dienThoai, ghiChu);

            // 5. Gọi hàm DAO để thực thi Sửa vào Database
            if (dao.updatePhongBan(pb)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cập nhật thông tin phòng ban thành công!");
                
                // Cập nhật lại JTable để thấy dữ liệu mới
                loadTable();
                
                // btnlamlaipbActionPerformed(evt); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Cập nhật thất bại! Vui lòng kiểm tra lại hệ thống.");
            }
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Lỗi định dạng Mã phòng ban!");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Lỗi hệ thống: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnsuapbActionPerformed

